/** Bundles the official STAC schemas so editor validation never fetches remote references. */
import {writeFile} from 'node:fs/promises';
const directory = new URL('../src/components/docs/schemas/', import.meta.url);
for (const version of ['1.0.0', '1.1.0']) {
  const documents = new Map();
  /** Fetches one schema and its referenced documents, preserving cycles. */
  async function collect(url) {
    if (documents.has(url)) return;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    const document = await response.json();
    documents.set(url, document);
    /** Discovers external references recursively. */
    async function visit(value) {
      if (!value || typeof value !== 'object') return;
      if (typeof value.$ref === 'string' && !value.$ref.startsWith('#')) {
        const reference = new URL(value.$ref, url);
        reference.hash = '';
        await collect(reference.href);
      }
      for (const child of Object.values(value)) await visit(child);
    }
    await visit(document);
  }
  const roots = {};
  for (const type of ['catalog', 'collection', 'item']) {
    roots[type] =
      `https://raw.githubusercontent.com/radiantearth/stac-spec/v${version}/${type}-spec/json-schema/${type}.json`;
    await collect(roots[type]);
  }
  const names = new Map([...documents.keys()].map((url, index) => [url, `document${index}`]));
  /** Rewrites document references into local JSON pointers. */
  function rewrite(value, url) {
    if (Array.isArray(value)) return value.map(child => rewrite(child, url));
    if (!value || typeof value !== 'object') return value;
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => key !== '$id')
        .map(([key, child]) => {
          if (key === '$ref' && typeof child === 'string') {
            const reference = new URL(child, url);
            const fragment = reference.hash.slice(1);
            reference.hash = '';
            return [key, `#/definitions/${names.get(reference.href)}${fragment}`];
          }
          return [key, rewrite(child, url)];
        })
    );
  }
  const definitions = Object.fromEntries(
    [...documents].map(([url, document]) => [names.get(url), rewrite(document, url)])
  );
  await writeFile(
    new URL(`stac-${version}.json`, directory),
    JSON.stringify(
      {
        $schema: 'http://json-schema.org/draft-07/schema#',
        $comment: `Official STAC ${version}; generated by website/scripts/update-stac-editor-schemas.mjs. Sources: ${[...documents.keys()].join(', ')}`,
        definitions,
        roots: Object.fromEntries(
          Object.entries(roots).map(([type, url]) => [type, `#/definitions/${names.get(url)}`])
        )
      },
      null,
      2
    ) + '\n'
  );
}
/** License notices for all vendored schema sources. */
const licenses = [
  ['STAC-LICENSE', 'https://raw.githubusercontent.com/radiantearth/stac-spec/v1.1.0/LICENSE'],
  ['GEOJSON-LICENSE', 'https://raw.githubusercontent.com/geojson/schema/main/license.md'],
  [
    'JSON-SCHEMA-LICENSE',
    'https://raw.githubusercontent.com/json-schema-org/json-schema-spec/main/LICENSE'
  ]
];
for (const [name, url] of licenses) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  await writeFile(new URL(name, directory), await response.text());
}

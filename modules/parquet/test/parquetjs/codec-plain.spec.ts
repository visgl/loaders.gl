test('ParquetCodec::PLAIN#should encode BYTE_ARRAY values', () => {
    const buf = PARQUET_CODECS.PLAIN.encodeValues('BYTE_ARRAY', ['one', bytes([0xde, 0xad, 0xbe, 0xef]), 'three']);
    expect(buf).toEqual(bytes([
        0x03, 0x00, 0x00, 0x00, // (3)
        0x6f, 0x6e, 0x65, // 'one'
        0x04, 0x00, 0x00, 0x00, // (4)
        0xde, 0xad, 0xbe, 0xef, // 0xdeadbeef
        0x05, 0x00, 0x00, 0x00, // (5)
        0x74, 0x68, 0x72, 0x65, 0x65 // 'three'
    ]));
});
test('ParquetCodec::PLAIN#should decode BYTE_ARRAY values', () => {
    const buf = {
        offset: 0,
        buffer: bytes([
            0x03, 0x00, 0x00, 0x00, // (3)
            0x6f, 0x6e, 0x65, // 'one'
            0x04, 0x00, 0x00, 0x00, // (4)
            0xde, 0xad, 0xbe, 0xef, // 0xdeadbeef
            0x05, 0x00, 0x00, 0x00, // (5)
            0x74, 0x68, 0x72, 0x65, 0x65 // 'three'
        ])
    };
    const vals = PARQUET_CODECS.PLAIN.decodeValues('BYTE_ARRAY', buf, 3, {});
    expect(buf.offset).toBe(24);
    expect(vals).toEqual([
        utf8Bytes('one'),
        bytes([0xde, 0xad, 0xbe, 0xef]),
        utf8Bytes('three')
    ]);
});
test('ParquetCodec::PLAIN#can retain BYTE_ARRAY views for direct materialization', () => {
    const buf = {
        offset: 0,
        buffer: bytes([0x03, 0x00, 0x00, 0x00, 0x6f, 0x6e, 0x65])
    };
    const vals = PARQUET_CODECS.PLAIN.decodeValues('BYTE_ARRAY', buf, 1, {
        retainByteArrayViews: true
    });
    expect(vals[0].buffer, 'retains the decoded page buffer').toBe(buf.buffer.buffer);
    expect(vals).toEqual([utf8Bytes('one')]);
});

import { expect, test } from "vitest";
import { PARQUET_CODECS } from '@loaders.gl/parquet/parquetjs/codecs';
import { assertArrayEqualEpsilon } from '../test-utils/assertions';
const UTF8_ENCODER = new TextEncoder();
function bytes(values: number[]): Uint8Array {
    return new Uint8Array(values);
}
function utf8Bytes(value: string): Uint8Array {
    return UTF8_ENCODER.encode(value);
}
test('ParquetCodec::PLAIN#should encode BOOLEAN values', () => {
    const buf = PARQUET_CODECS.PLAIN.encodeValues('BOOLEAN', [true, false, true, true, false, true, false, false]);
    expect(buf).toEqual(bytes([0x2d])); // b101101
});
test('ParquetCodec::PLAIN#should decode BOOLEAN values', () => {
    const buf = {
        offset: 0,
        buffer: bytes([0x2d]) // b101101
    };
    const vals = PARQUET_CODECS.PLAIN.decodeValues('BOOLEAN', buf, 8, {});
    expect(buf.offset).toBe(1);
    expect(vals).toEqual([true, false, true, true, false, true, false, false]);
});
